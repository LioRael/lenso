#[test]
fn local_legacy_guest_reuses_unchanged_projection_without_an_exporter() {
    let consumer = tempfile::tempdir().unwrap();
    let root = consumer.path().join("contracts/text");
    descriptor(&root, "example.text@1");
    let digest = load_descriptor(&root.join("capability.json"))
        .unwrap()
        .descriptor_digest()
        .to_owned();
    let output = root.join("generated/text.rs");
    fs::create_dir_all(output.parent().unwrap()).unwrap();
    let prebuilt = format!(
        "// @generated by lenso-contract-codegen 0.8.2\npub const DESCRIPTOR_DIGEST: &str = \"{digest}\";\n"
    );
    fs::write(&output, &prebuilt).unwrap();
    let modified = fs::metadata(&output).unwrap().modified().unwrap();
    // Locked Cargo metadata describes a direct Guest SDK 0.4 dependency and
    // no codegen build dependency. Synchronization must not execute Cargo.
    let package = json!({"id":"text-contract", "dependencies":[]});
    let metadata = json!({
        "workspace_root":consumer.path(),
        "packages":[{"id":"legacy-sdk","name":"lenso-guest-sdk","version":"0.4.0"}],
        "resolve":{"nodes":[{"id":"text-contract","deps":[{"pkg":"legacy-sdk"}]}]}
    });
    let selected = || {
        let mut contracts = BTreeMap::new();
        insert(
            &mut contracts,
            root.clone(),
            json!({"descriptor":"capability.json","projection":"rust","output":"generated/text.rs"}),
            Some((package.clone(), metadata.clone())),
        )
        .unwrap();
        assert!(targets_legacy_guest(contracts.get(&root).unwrap()));
        contracts
    };
    let evidence = synchronize_selected(consumer.path(), selected()).unwrap();
    assert_eq!(fs::read_to_string(&output).unwrap(), prebuilt);
    assert_eq!(fs::metadata(&output).unwrap().modified().unwrap(), modified);
    assert_eq!(evidence[0].files[&output], file_digest(&output).unwrap());
    // A generated marker alone is insufficient: a stale projection still
    // requires an explicit compatible generator, and is not overwritten.
    let stale = prebuilt.replace(&digest, "stale-contract-digest");
    fs::write(&output, &stale).unwrap();
    let error = synchronize_selected(consumer.path(), selected())
        .unwrap_err()
        .to_string();
    assert!(error.contains("compatible lenso-contract-codegen build-dependency"));
    assert_eq!(fs::read_to_string(&output).unwrap(), stale);
}

#[test]
fn configured_roots_exclusions_and_read_only_freshness_check() {
    let root = tempfile::tempdir().unwrap();
    descriptor(&root.path().join("interfaces/used"), "example.used@1");
    descriptor(&root.path().join("interfaces/ignored"), "example.ignored@1");
    fs::write(
        root.path().join("interfaces/ignored/capability.json"),
        "invalid",
    )
    .unwrap();
    fs::write(
        root.path().join("lenso.toml"),
        "[contracts]\nroots=['interfaces']\nexclude_paths=['interfaces/ignored']\n",
    )
    .unwrap();
    let evidence = synchronize(root.path(), &[]).unwrap();
    assert_eq!(evidence.len(), 1);
    fs::write(
        root.path().join(".lenso/contracts/freshness.json"),
        serde_json::to_vec(&evidence).unwrap(),
    )
    .unwrap();
    check(root.path()).unwrap();
    let output = root.path().join("interfaces/used/generated/text.ts");
    fs::write(&output, "// @generated by lenso-contract-codegen\nstale").unwrap();
    assert!(check(root.path()).is_err());
    assert_eq!(
        fs::read_to_string(output).unwrap(),
        "// @generated by lenso-contract-codegen\nstale"
    );
    assert!(!root.path().join("interfaces/ignored/generated").exists());
}

