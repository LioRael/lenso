#[test]
fn published_legacy_projection_is_reused_in_consumer_output_with_source_freshness() {
    for source in [
        "registry+https://example.invalid/index",
        "git+https://example.invalid/contracts?rev=locked",
    ] {
        let consumer = tempfile::tempdir().unwrap();
        let dependency = tempfile::tempdir().unwrap();
        descriptor(dependency.path(), "example.external@1");
        let digest = load_descriptor(&dependency.path().join("capability.json"))
            .unwrap()
            .descriptor_digest()
            .to_owned();
        let original = dependency.path().join("src/generated.rs");
        fs::create_dir(original.parent().unwrap()).unwrap();
        let prebuilt = format!(
            "// @generated by lenso-contract-codegen; do not edit.\npub const DESCRIPTOR_DIGEST: &str = \"{digest}\";\n"
        );
        fs::write(&original, &prebuilt).unwrap();
        fs::write(
            dependency.path().join("build.rs"),
            "fn main() { panic!(\"must not execute\"); }",
        )
        .unwrap();
        fs::write(
            consumer.path().join("Cargo.lock"),
            "version = 4\n# materialized locked fixture\n",
        )
        .unwrap();
        let before = lenso_engine::Snapshot::read(dependency.path()).unwrap();
        let package =
            json!({"id":format!("{source}#external@1.0.0"),"source":source,"dependencies":[]});
        let metadata = json!({"workspace_root":consumer.path(),"packages":[{"id":"legacy-sdk","name":"lenso-guest-sdk","version":"0.4.0"}],"resolve":{"nodes":[{"id":package["id"],"deps":[{"pkg":"legacy-sdk"}]}]}});
        let selected = |module: Option<&str>| {
            let mut contracts = BTreeMap::new();
            insert(&mut contracts, dependency.path().into(), json!({"descriptor":"capability.json","projection":"rust-runtime","output":"src/generated.rs"}), Some((package.clone(),metadata.clone()))).unwrap();
            let config = Configuration {
                dependency_projections: vec![Projection {
                    projection: "rust-runtime".into(),
                    output: "client.rs".into(),
                    module: module.map(str::to_owned),
                }],
                ..Configuration::default()
            };
            configure_external(
                consumer.path(),
                &package,
                &config,
                contracts.get_mut(dependency.path()).unwrap(),
            )
            .unwrap();
            contracts
        };
        let contracts = selected(None);
        let output = contracts[dependency.path()]
            .output_root
            .as_ref()
            .unwrap()
            .join("client.rs");
        let evidence = synchronize_selected(consumer.path(), contracts).unwrap();
        assert_eq!(fs::read_to_string(&output).unwrap(), prebuilt);
        assert_eq!(
            evidence[0].files[&original],
            file_digest(&original).unwrap()
        );
        assert_eq!(evidence[0].files[&output], file_digest(&output).unwrap());
        assert_eq!(
            serde_json::to_value(before).unwrap(),
            serde_json::to_value(lenso_engine::Snapshot::read(dependency.path()).unwrap()).unwrap()
        );
        // A different module cannot silently reuse an incompatible prebuilt.
        assert!(
            synchronize_selected(consumer.path(), selected(Some("named")))
                .unwrap_err()
                .to_string()
                .contains("compatible lenso-contract-codegen build-dependency")
        );
        fs::write(&original, prebuilt.replace(&digest, "stale")).unwrap();
        assert!(
            synchronize_selected(consumer.path(), selected(None))
                .unwrap_err()
                .to_string()
                .contains("compatible lenso-contract-codegen build-dependency")
        );
    }
}

#[test]
fn unlocked_dependencies_are_diagnosed_without_resolution_or_borrowing_parent_lock() {
    let parent = tempfile::tempdir().unwrap();
    fs::write(parent.path().join("Cargo.lock"), "unrelated parent lock").unwrap();
    let root = parent.path().join("fresh");
    fs::create_dir_all(root.join("src")).unwrap();
    fs::write(root.join("src/lib.rs"), "").unwrap();
    let manifest = root.join("Cargo.toml");
    fs::write(&manifest, "[package]\nname='fresh'\nversion='0.1.0'\nedition='2024'\n[workspace]\n[dependencies]\nlenso-unprepared-dependency-fixture='=99.0.0'\n").unwrap();
    let before = lenso_engine::Snapshot::read(parent.path()).unwrap();
    let error = cargo_metadata(&manifest).unwrap_err().to_string();
    assert!(
        error.contains("Cargo dependencies are not prepared"),
        "{error}"
    );
    assert!(error.contains("cargo generate-lockfile --manifest-path"));
    assert!(error.contains("--no-install"));
    assert!(!root.join("Cargo.lock").exists());
    assert_eq!(
        serde_json::to_value(before).unwrap(),
        serde_json::to_value(lenso_engine::Snapshot::read(parent.path()).unwrap()).unwrap()
    );
}

