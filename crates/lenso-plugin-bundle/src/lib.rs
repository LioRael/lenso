/// Verified closure of one immutable Plugin Release.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct VerifiedBundle {
    pub plugin_id: String,
    pub release_version: String,
    pub manifest_digest: String,
    /// Executable Artifact digests; V6 Cargo inputs remain in the verified Manifest closure.
    pub artifact_digests: Vec<String>,
    pub product_metadata_digests: Vec<String>,
}

/// A Plugin authoring or immutable Bundle invariant failed closed.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum BundleError {
    InvalidManifest(String),
    InvalidBundle(String),
    DigestMismatch(String),
    Io(String),
    Wasm(String),
}

impl fmt::Display for BundleError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::InvalidManifest(detail) => write!(formatter, "invalid Plugin Manifest: {detail}"),
            Self::InvalidBundle(detail) => write!(formatter, "invalid Plugin Bundle: {detail}"),
            Self::DigestMismatch(subject) => write!(formatter, "digest mismatch for {subject}"),
            Self::Io(detail) => formatter.write_str(detail),
            Self::Wasm(detail) => write!(
                formatter,
                "failed to encode WebAssembly Component: {detail}"
            ),
        }
    }
}

impl std::error::Error for BundleError {}

/// Builds a one-entry V2 Plugin Bundle entirely from package and source evidence.
pub fn build_source_plugin_bundle(
    build: &SourcePluginBuild,
) -> Result<VerifiedBundle, BundleError> {
    if build.output.exists() {
        return invalid_bundle(format!(
            "output `{}` already exists",
            build.output.display()
        ));
    }
    let package_bytes = read_regular_file(&build.package_manifest, "Cargo manifest")?;
    let package = toml::from_slice::<CargoManifest>(&package_bytes)
        .map_err(|error| BundleError::InvalidManifest(error.to_string()))?;
    let module = read_regular_file(&build.wasm_module, "Plugin Wasm module")?;
    let component = wit_component::ComponentEncoder::default()
        .module(&module)
        .map_err(|error| BundleError::Wasm(error.to_string()))?
        .validate(true)
        .encode()
        .map_err(|error| BundleError::Wasm(error.to_string()))?;
    let runtime_descriptor = extract_plugin_descriptor(&component)?;
    let artifact = PluginArtifactV2 {
        path: "plugin.wasm".to_owned(),
        digest: sha256_digest(&component),
        size: u64::try_from(component.len())
            .map_err(|_| BundleError::InvalidBundle("Artifact size exceeds u64".to_owned()))?,
        media_type: "application/wasm".to_owned(),
        target: "wasm32-unknown-unknown".to_owned(),
    };
    let descriptor = portable_plugin_descriptor(
        &package.package.metadata.lenso.plugin_id,
        &package.package.version,
        &package.package.metadata.lenso.root_slot,
        &artifact.digest,
        &runtime_descriptor,
        PortableRuntime {
            execution_class: "lenso.wasm-component@1",
            authoring_version: 1,
            runtime_profile: "lenso.wasm-component@1",
        },
    )?;
    let document = SourceManifestDocument::from_value(PluginManifestV2 {
        schema_version: 2,
        plugin_id: package.package.metadata.lenso.plugin_id,
        release_version: package.package.version,
        artifact,
        entry: PluginEntryV2 { descriptor },
    })?;

    let output_parent = build.output.parent().unwrap_or_else(|| Path::new("."));
    fs::create_dir_all(output_parent).map_err(io_error)?;
    let staging = tempfile::Builder::new()
        .prefix(".lenso-plugin-")
        .tempdir_in(output_parent)
        .map_err(io_error)?;
    write_bundle_file(staging.path(), &document.value.artifact.path, &component)?;
    fs::write(staging.path().join(MANIFEST_FILE), &document.bytes).map_err(io_error)?;
    fs::rename(staging.path(), &build.output).map_err(io_error)?;
    verify_bundle_directory(&build.output)
}

/// Builds a one-entry V2 Process Plugin Bundle from generated source evidence.
pub fn build_source_process_plugin_bundle(
    build: &SourceProcessPluginBuild,
) -> Result<VerifiedBundle, BundleError> {
    if build.output.exists() {
        return invalid_bundle(format!(
            "output `{}` already exists",
            build.output.display()
        ));
    }
    if build.target.trim().is_empty() {
        return invalid_manifest("Process target is empty");
    }
    let package_bytes = read_regular_file(&build.package_manifest, "Cargo manifest")?;
    let package = toml::from_slice::<CargoManifest>(&package_bytes)
        .map_err(|error| BundleError::InvalidManifest(error.to_string()))?;
    let executable = read_regular_file(&build.executable, "Process executable")?;
    let encoded_descriptor = read_regular_file(&build.runtime_descriptor, "runtime descriptor")?;
    let artifact = PluginArtifactV2 {
        path: if cfg!(windows) {
            "plugin.exe".to_owned()
        } else {
            "plugin".to_owned()
        },
        digest: sha256_digest(&executable),
        size: u64::try_from(executable.len())
            .map_err(|_| BundleError::InvalidBundle("Artifact size exceeds u64".to_owned()))?,
        media_type: "application/vnd.lenso.process".to_owned(),
        target: build.target.clone(),
    };
    let descriptor = portable_plugin_descriptor(
        &package.package.metadata.lenso.plugin_id,
        &package.package.version,
        &package.package.metadata.lenso.root_slot,
        &artifact.digest,
        &encoded_descriptor,
        PortableRuntime {
            execution_class: "lenso.process@1",
            authoring_version: build.authoring_version,
            runtime_profile: &build.runtime_profile,
        },
    )?;
    let document = SourceManifestDocument::from_value(PluginManifestV2 {
        schema_version: 2,
        plugin_id: package.package.metadata.lenso.plugin_id,
        release_version: package.package.version,
        artifact,
        entry: PluginEntryV2 { descriptor },
    })?;

    let output_parent = build.output.parent().unwrap_or_else(|| Path::new("."));
    fs::create_dir_all(output_parent).map_err(io_error)?;
    let staging = tempfile::Builder::new()
        .prefix(".lenso-plugin-")
        .tempdir_in(output_parent)
        .map_err(io_error)?;
    write_bundle_file(staging.path(), &document.value.artifact.path, &executable)?;
    preserve_executable_permissions(
        &build.executable,
        &staging.path().join(&document.value.artifact.path),
    )?;
    fs::write(staging.path().join(MANIFEST_FILE), &document.bytes).map_err(io_error)?;
    fs::rename(staging.path(), &build.output).map_err(io_error)?;
    verify_bundle_directory(&build.output)
}

/// Materializes a V4 Plugin Bundle from one contract and built implementation Artifacts.
pub fn build_source_plugin_release_bundle(
    build: &SourcePluginReleaseBuild,
) -> Result<VerifiedBundle, BundleError> {
    if build.output.exists() {
        return invalid_bundle(format!(
            "output `{}` already exists",
            build.output.display()
        ));
    }
    let mut files = Vec::with_capacity(build.implementations.len());
    let mut implementations = Vec::with_capacity(build.implementations.len());
    for source in &build.implementations {
        let bytes = read_regular_file(&source.artifact, "Plugin implementation Artifact")?;
        let digest = sha256_digest(&bytes);
        let artifact = PluginArtifactV2 {
            path: source.bundle_path.clone(),
            digest: digest.clone(),
            size: u64::try_from(bytes.len())
                .map_err(|_| BundleError::InvalidBundle("Artifact size exceeds u64".to_owned()))?,
            media_type: source.media_type.clone(),
            target: source.target.clone(),
        };
        implementations.push(PluginImplementationV4 {
            id: source.id.clone(),
            host_targets: source.host_targets.clone(),
            artifact,
            runtime: PluginImplementation::new(
                build.contract.plugin_id(),
                digest,
                &source.entrypoint,
                source.execution_class.clone(),
            )
            .with_runtime_profile(&source.runtime_profile)
            .with_required_target_capabilities(source.required_target_capabilities.iter().copied()),
        });
        files.push((source, bytes));
    }
    implementations.sort_by(|left, right| left.id.cmp(&right.id));
    let manifest = PluginManifestV4 {
        schema_version: 4,
        contract: build.contract.clone(),
        implementations,
    };
    validate_v4_manifest(&manifest)?;
    let bytes = serde_json::to_vec(&manifest)
        .map_err(|error| BundleError::InvalidManifest(error.to_string()))?;

    let output_parent = build.output.parent().unwrap_or_else(|| Path::new("."));
    fs::create_dir_all(output_parent).map_err(io_error)?;
    let staging = tempfile::Builder::new()
        .prefix(".lenso-plugin-")
        .tempdir_in(output_parent)
        .map_err(io_error)?;
    for (source, artifact) in files {
        write_bundle_file(staging.path(), &source.bundle_path, &artifact)?;
        if source.media_type == "application/vnd.lenso.process" {
            preserve_executable_permissions(
                &source.artifact,
                &staging.path().join(&source.bundle_path),
            )?;
        }
    }
    fs::write(staging.path().join(MANIFEST_FILE), bytes).map_err(io_error)?;
    fs::rename(staging.path(), &build.output).map_err(io_error)?;
    verify_bundle_directory(&build.output)
}

/// Materializes a V5 release without executing any source Artifact.
pub fn build_source_plugin_release_bundle_v5(
    build: &SourcePluginReleaseBuildV5,
) -> Result<VerifiedBundle, BundleError> {
    if build.output.exists() {
        return invalid_bundle(format!(
            "output `{}` already exists",
            build.output.display()
        ));
    }
    let mut files = Vec::new();
    let mut implementations = Vec::with_capacity(build.implementations.len());
    for group in &build.implementations {
        let mut variants = Vec::with_capacity(group.variants.len());
        for source in &group.variants {
            let bytes = read_regular_file(&source.artifact, "Plugin variant Artifact")?;
            let digest = sha256_digest(&bytes);
            let artifact = PluginArtifactV2 {
                path: source.bundle_path.clone(),
                digest: digest.clone(),
                size: u64::try_from(bytes.len()).map_err(|_| {
                    BundleError::InvalidBundle("Artifact size exceeds u64".to_owned())
                })?,
                media_type: source.media_type.clone(),
                target: source.target.clone(),
            };
            variants.push(PluginVariantV5 {
                id: source.id.clone(),
                host_targets: source.host_targets.clone(),
                artifact,
                runtime: PluginImplementation::new(
                    build.contract.plugin_id(),
                    digest,
                    &source.entrypoint,
                    source.execution_class.clone(),
                )
                .with_runtime_profile(&source.runtime_profile)
                .with_required_target_capabilities(
                    source.required_target_capabilities.iter().copied(),
                ),
            });
            files.push((source, bytes));
        }
        variants.sort_by(|left, right| left.id.cmp(&right.id));
        implementations.push(PluginImplementationV5 {
            id: group.id.clone(),
            variants,
        });
    }
    implementations.sort_by(|left, right| left.id.cmp(&right.id));
    let manifest = PluginManifestV5 {
        schema_version: 5,
        contract: build.contract.clone(),
        implementations,
    };
    validate_v5_manifest(&manifest)?;
    let bytes = canonical_manifest_bytes(&PluginManifest::V5(manifest))?;

    let parent = build.output.parent().unwrap_or_else(|| Path::new("."));
    fs::create_dir_all(parent).map_err(io_error)?;
    let staging = tempfile::Builder::new()
        .prefix(".lenso-plugin-")
        .tempdir_in(parent)
        .map_err(io_error)?;
    for (source, bytes) in files {
        write_bundle_file(staging.path(), &source.bundle_path, &bytes)?;
        if source.media_type == "application/vnd.lenso.process" {
            preserve_executable_permissions(
                &source.artifact,
                &staging.path().join(&source.bundle_path),
            )?;
        }
    }
    fs::write(staging.path().join(MANIFEST_FILE), bytes).map_err(io_error)?;
    fs::rename(staging.path(), &build.output).map_err(io_error)?;
    verify_bundle_directory(&build.output)
}

/// Materializes a V6 release. A Cargo input is copied and verified, never built or loaded.
pub fn build_source_plugin_release_bundle_v6(
    build: &SourcePluginReleaseBuildV6,
) -> Result<VerifiedBundle, BundleError> {
    if build.output.exists() {
        return invalid_bundle(format!(
            "output `{}` already exists",
            build.output.display()
        ));
    }
    let limits = BundleVerificationLimits::default();
    validate_verification_limits(&limits)?;
    let mut files = Vec::new();
    let mut input_bytes = 0_u64;
    let mut implementations = Vec::with_capacity(build.implementations.len());
    for group in &build.implementations {
        let mut variants = Vec::with_capacity(group.variants.len());
        for source in &group.variants {
            if files.len() >= limits.max_file_count.saturating_sub(1) {
                return invalid_bundle("V6 source inputs exceed the Bundle file-count limit");
            }
            let remaining = limits.max_total_bytes.saturating_sub(input_bytes);
            let (variant, file) = materialize_source_variant_v6(
                &build.contract,
                source,
                limits.max_file_bytes.min(remaining),
            )?;
            input_bytes = input_bytes
                .checked_add(u64::try_from(file.2.len()).unwrap_or(u64::MAX))
                .ok_or_else(|| BundleError::InvalidBundle("V6 source size overflow".to_owned()))?;
            variants.push(variant);
            files.push(file);
        }
        variants.sort_by(|left, right| left.id.cmp(&right.id));
        implementations.push(PluginImplementationV6 {
            id: group.id.clone(),
            variants,
        });
    }
    implementations.sort_by(|left, right| left.id.cmp(&right.id));
    let manifest = PluginManifestV6 {
        schema_version: 6,
        contract: build.contract.clone(),
        implementations,
    };
    validate_v6_manifest(&manifest)?;
    let bytes = canonical_manifest_bytes(&PluginManifest::V6(manifest))?;
    if u64::try_from(bytes.len()).unwrap_or(u64::MAX) > limits.max_manifest_bytes
        || input_bytes
            .checked_add(u64::try_from(bytes.len()).unwrap_or(u64::MAX))
            .is_none_or(|total| total > limits.max_total_bytes)
    {
        return invalid_bundle("V6 source closure exceeds the Bundle size limits");
    }

    let parent = build.output.parent().unwrap_or_else(|| Path::new("."));
    fs::create_dir_all(parent).map_err(io_error)?;
    let staging = tempfile::Builder::new()
        .prefix(".lenso-plugin-")
        .tempdir_in(parent)
        .map_err(io_error)?;
    for (source_path, bundle_path, bytes, is_executable) in files {
        write_bundle_file(staging.path(), &bundle_path, &bytes)?;
        if is_executable {
            preserve_executable_permissions(&source_path, &staging.path().join(&bundle_path))?;
        }
    }
    fs::write(staging.path().join(MANIFEST_FILE), bytes).map_err(io_error)?;
    fs::rename(staging.path(), &build.output).map_err(io_error)?;
    verify_bundle_directory(&build.output)
}

type SourceVariantFileV6 = (PathBuf, String, Vec<u8>, bool);

fn materialize_source_variant_v6(
    contract: &PluginContract,
    source: &SourcePluginVariantV6,
    max_file_bytes: u64,
) -> Result<(PluginVariantV6, SourceVariantFileV6), BundleError> {
    let (path, bundle_path, is_executable) = match &source.input {
        SourcePluginVariantInputV6::Artifact {
            path,
            bundle_path,
            media_type,
            ..
        } => (
            path,
            bundle_path,
            media_type == "application/vnd.lenso.process",
        ),
        SourcePluginVariantInputV6::CargoBuildInput {
            path, bundle_path, ..
        } => (path, bundle_path, false),
    };
    let bytes = read_regular_file_bounded(path, "Plugin variant input", max_file_bytes)?;
    let digest = sha256_digest(&bytes);
    let size = u64::try_from(bytes.len())
        .map_err(|_| BundleError::InvalidBundle("Input size exceeds u64".to_owned()))?;
    let input = match &source.input {
        SourcePluginVariantInputV6::Artifact {
            media_type, target, ..
        } => PluginVariantInputV6::Artifact {
            artifact: PluginArtifactV2 {
                path: bundle_path.clone(),
                digest: digest.clone(),
                size,
                media_type: media_type.clone(),
                target: target.clone(),
            },
        },
        SourcePluginVariantInputV6::CargoBuildInput {
            package, version, ..
        } => PluginVariantInputV6::CargoBuildInput {
            build_input: PluginCargoBuildInputV6 {
                path: bundle_path.clone(),
                digest: digest.clone(),
                size,
                package: package.clone(),
                version: version.clone(),
            },
        },
    };
    let mut execution_requirements = source.execution_requirements.clone();
    execution_requirements.sort_unstable();
    Ok((
        PluginVariantV6 {
            id: source.id.clone(),
            host_targets: source.host_targets.clone(),
            input,
            runtime: PluginImplementation::new(
                contract.plugin_id(),
                digest,
                &source.entrypoint,
                source.execution_class.clone(),
            )
            .with_runtime_profile(&source.runtime_profile)
            .with_required_target_capabilities(source.required_target_capabilities.iter().copied()),
            execution_requirements,
        },
        (path.clone(), bundle_path.clone(), bytes, is_executable),
    ))
}

/// Verifies an already materialized directory as an exact immutable Bundle closure.
pub fn verify_bundle_directory(root: &Path) -> Result<VerifiedBundle, BundleError> {
    verify_bundle_directory_with_limits(root, &BundleVerificationLimits::default())
}

/// Verifies one Bundle with explicit Host-owned resource bounds.
pub fn verify_bundle_directory_with_limits(
    root: &Path,
    limits: &BundleVerificationLimits,
) -> Result<VerifiedBundle, BundleError> {
    verify_bundle_document_with_limits(root, limits).map(|(verified, _)| verified)
}

fn verify_bundle_document_with_limits(
    root: &Path,
    limits: &BundleVerificationLimits,
) -> Result<(VerifiedBundle, ManifestDocument), BundleError> {
    verify_bundle_document_with_limits_after_manifest_read(root, limits, || {})
}

fn verify_bundle_document_with_limits_after_manifest_read(
    root: &Path,
    limits: &BundleVerificationLimits,
    after_manifest_read: impl FnOnce(),
) -> Result<(VerifiedBundle, ManifestDocument), BundleError> {
    validate_verification_limits(limits)?;
    let manifest_path = root.join(MANIFEST_FILE);
    let manifest_bytes =
        read_regular_file_bounded(&manifest_path, "Plugin Manifest", limits.max_manifest_bytes)?;
    after_manifest_read();
    let mut files = BTreeMap::new();
    let mut total_size = 0_u64;
    let mut entry_count = 0_usize;
    collect_bundle_files(
        root,
        root,
        0,
        limits,
        &mut entry_count,
        &mut total_size,
        &mut files,
    )?;
    let manifest_summary = files
        .remove(MANIFEST_FILE)
        .ok_or_else(|| BundleError::InvalidBundle("Bundle is missing its Manifest".to_owned()))?;
    if manifest_summary.size != u64::try_from(manifest_bytes.len()).unwrap_or(u64::MAX)
        || manifest_summary.digest != sha256_digest(&manifest_bytes)
    {
        return invalid_bundle("Plugin Manifest changed during Bundle verification");
    }
    let manifest = ManifestDocument::parse(&manifest_bytes)?;
    let verified = verify_manifest_bundle_files(root, &manifest, &files, limits)?;
    Ok((verified, manifest))
}

/// Strictly reads either supported Plugin Manifest version from a verified Bundle.
pub fn read_bundle_manifest(root: &Path) -> Result<PluginManifest, BundleError> {
    read_bundle_manifest_with_limits(root, &BundleVerificationLimits::default())
}

/// Reads a Manifest only after verifying its entire Bundle under Host limits.
pub fn read_bundle_manifest_with_limits(
    root: &Path,
    limits: &BundleVerificationLimits,
) -> Result<PluginManifest, BundleError> {
    read_verified_bundle_with_limits(root, limits).map(|(_, manifest)| manifest)
}

/// Returns exact verified closure evidence together with its parsed Manifest.
pub fn read_verified_bundle_with_limits(
    root: &Path,
    limits: &BundleVerificationLimits,
) -> Result<(VerifiedBundle, PluginManifest), BundleError> {
    let (verified, manifest) = verify_bundle_document_with_limits(root, limits)?;
    Ok((verified, manifest.value))
}

/// Reopens exact verified Cargo source bytes for a Host build, never execution.
///
/// Call this after verifying the enclosing Bundle Manifest and after checking
/// the independently authorized release identity. The bounded read repeats
/// digest, size, Cargo coordinate, and Plugin ID checks before use.
pub fn read_verified_cargo_build_input(
    root: &Path,
    input: &PluginCargoBuildInputV6,
    plugin_id: &str,
    max_file_bytes: u64,
) -> Result<Vec<u8>, BundleError> {
    validate_cargo_build_input(input)?;
    let bytes =
        read_regular_file_bounded(&root.join(&input.path), "Cargo build input", max_file_bytes)?;
    if u64::try_from(bytes.len()).unwrap_or(u64::MAX) != input.size
        || sha256_digest(&bytes) != input.digest
    {
        return Err(BundleError::DigestMismatch(input.path.clone()));
    }
    verify_cargo_build_input(&bytes, input, plugin_id)?;
    Ok(bytes)
}

fn verify_manifest_bundle_files(
    root: &Path,
    manifest: &ManifestDocument,
    files: &BTreeMap<String, BundleFileSummary>,
    limits: &BundleVerificationLimits,
) -> Result<VerifiedBundle, BundleError> {
    match &manifest.value {
        PluginManifest::V2(value) => verify_source_bundle_files(
            &SourceManifestDocument {
                value: value.clone(),
                bytes: Vec::new(),
                digest: manifest.digest.clone(),
            },
            root,
            files,
            limits,
        ),
        PluginManifest::V3(value) => {
            verify_v3_bundle_files(root, value, &manifest.digest, files, limits)
        }
        PluginManifest::V4(value) => {
            verify_v4_bundle_files(root, value, &manifest.digest, files, limits)
        }
        PluginManifest::V5(value) => {
            verify_v5_bundle_files(root, value, &manifest.digest, files, limits)
        }
        PluginManifest::V6(value) => {
            verify_v6_bundle_files(root, value, &manifest.digest, files, limits)
        }
    }
}

fn verify_v3_bundle_files(
    root: &Path,
    manifest: &PluginManifestV3,
    manifest_digest: &str,
    files: &BTreeMap<String, BundleFileSummary>,
    limits: &BundleVerificationLimits,
) -> Result<VerifiedBundle, BundleError> {
    verify_profiled_bundle_files(
        root,
        &manifest.contract,
        manifest
            .implementations
            .iter()
            .map(|implementation| (&implementation.artifact, &implementation.runtime)),
        manifest.implementations.len(),
        manifest_digest,
        files,
        limits,
        "V3",
    )
}

#[allow(clippy::too_many_arguments)]
fn verify_profiled_bundle_files<'a>(
    root: &Path,
    contract: &PluginContract,
    implementations: impl Iterator<Item = (&'a PluginArtifactV2, &'a PluginImplementation)>,
    implementation_count: usize,
    manifest_digest: &str,
    files: &BTreeMap<String, BundleFileSummary>,
    limits: &BundleVerificationLimits,
    schema: &str,
) -> Result<VerifiedBundle, BundleError> {
    if files.len() != implementation_count {
        return invalid_bundle(format!(
            "{schema} Bundle closure does not equal its implementation Artifacts"
        ));
    }
    let mut artifact_digests = Vec::with_capacity(implementation_count);
    for (artifact, runtime) in implementations {
        let Some(summary) = files.get(&artifact.path) else {
            return invalid_bundle(format!("{schema} Bundle is missing `{}`", artifact.path));
        };
        if artifact.size != summary.size || artifact.digest != summary.digest {
            return Err(BundleError::DigestMismatch(artifact.path.clone()));
        }
        if runtime.runtime_package_revision() != artifact.digest {
            return invalid_manifest("implementation revision must equal its Artifact digest");
        }
        if artifact.media_type == "application/wasm" {
            let bytes = read_verified_bundle_artifact(root, artifact, limits)?;
            let encoded = extract_plugin_descriptor(&bytes)?;
            let derived = portable_plugin_descriptor(
                contract.plugin_id(),
                contract.release_version(),
                contract.root_slot(),
                &artifact.digest,
                &encoded,
                PortableRuntime {
                    execution_class: runtime.execution_class().as_str(),
                    authoring_version: contract.authoring_version(),
                    runtime_profile: runtime.runtime_profile(),
                },
            )?;
            // Target requirements are conservative publisher-owned admission
            // constraints, not Guest ABI claims. Project them onto the
            // source-derived descriptor before comparing the complete choice.
            let derived = serde_json::from_value::<PluginDescriptor>(derived)
                .map_err(|error| BundleError::InvalidManifest(error.to_string()))?
                .with_required_target_capabilities(
                    runtime.required_target_capabilities().iter().copied(),
                );
            if derived.contract() != *contract || derived.implementation() != *runtime {
                return invalid_bundle(format!(
                    "Wasm source descriptor does not match its {schema} Contract and implementation"
                ));
            }
        }
        artifact_digests.push(artifact.digest.clone());
    }
    Ok(VerifiedBundle {
        plugin_id: contract.plugin_id().to_owned(),
        release_version: contract.release_version().to_owned(),
        manifest_digest: manifest_digest.to_owned(),
        artifact_digests,
        product_metadata_digests: Vec::new(),
    })
}

