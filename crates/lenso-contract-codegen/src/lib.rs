/// A parsed Descriptor `SemVer`.
#[derive(Clone, Debug, Eq, Ord, PartialEq, PartialOrd)]
struct Version(semver::Version);

impl Version {
    fn parse(value: &str) -> Result<Self, CodegenError> {
        semver::Version::parse(value)
            .map(Self)
            .map_err(|error| CodegenError::InvalidDescriptor {
                detail: format!("Descriptor version `{value}` is not valid SemVer: {error}"),
            })
    }

    const fn major(&self) -> u64 {
        self.0.major
    }

    const fn minor(&self) -> u64 {
        self.0.minor
    }
}

fn parse_numeric_component(value: &str) -> Option<u64> {
    (!value.is_empty() && (value == "0" || !value.starts_with('0')))
        .then(|| value.parse().ok())
        .flatten()
}

#[derive(Clone, Debug)]
struct Operation {
    name: String,
    interaction: String,
    request_schema: Value,
    response_schema: Value,
    domain_error_schema: Value,
}

fn contract_ir(descriptor: &Descriptor) -> ContractIr {
    ContractIr {
        capability_id: descriptor.capability_id.clone(),
        version: descriptor.version.clone(),
        descriptor_digest: descriptor.digest.clone(),
        portable: descriptor.portable,
        cross_lane_transfer: descriptor.cross_lane_transfer,
        operations: descriptor
            .operations
            .iter()
            .map(|operation| OperationIr {
                name: operation.name.clone(),
                interaction: operation.interaction.clone(),
                request: type_ir_from_schema(&operation.request_schema),
                response: type_ir_from_schema(&operation.response_schema),
                domain_errors: error_variant_ir_definitions(&operation.domain_error_schema),
            })
            .collect(),
    }
}

fn type_ir_from_schema(schema: &Value) -> TypeIr {
    if let Some(types) = schema.get("type").and_then(Value::as_array) {
        let non_null_types = types
            .iter()
            .filter(|schema_type| *schema_type != "null")
            .cloned()
            .collect::<Vec<_>>();
        if non_null_types.is_empty() {
            return TypeIr::Null;
        }
        if non_null_types.len() == 1 {
            let mut narrowed = schema.as_object().cloned().unwrap_or_default();
            narrowed.insert("type".to_owned(), non_null_types[0].clone());
            let base = type_ir_non_null(&Value::Object(narrowed));
            return if non_null_types.len() == types.len() {
                base
            } else {
                TypeIr::Nullable(Box::new(base))
            };
        }
    }
    type_ir_non_null(schema)
}

fn type_ir_non_null(schema: &Value) -> TypeIr {
    let Some(object) = schema.as_object() else {
        return TypeIr::Any;
    };
    if let Some(values) = object.get("enum").and_then(Value::as_array) {
        return TypeIr::Enum {
            name: schema_declared_type_name(object),
            values: values
                .iter()
                .filter_map(Value::as_str)
                .map(ToOwned::to_owned)
                .collect(),
        };
    }
    if let Some(schema_type) = object.get("type").and_then(Value::as_str) {
        return match schema_type {
            "object" => {
                let required = required_fields(schema);
                let mut properties = object
                    .get("properties")
                    .and_then(Value::as_object)
                    .into_iter()
                    .flatten()
                    .collect::<Vec<_>>();
                // Projection order is intentionally independent from JSON map
                // insertion order. Source authoring preserves declaration order
                // for locked snapshots; language backends retain the historical
                // canonical name order.
                properties.sort_unstable_by_key(|(name, _)| *name);
                let fields = properties
                    .into_iter()
                    .map(|(name, schema)| {
                        let ty = type_ir_from_schema(schema);
                        let ty = if name.ends_with("_json") && ty == TypeIr::String {
                            TypeIr::RawJson
                        } else {
                            ty
                        };
                        FieldIr {
                            name: name.clone(),
                            required: required.contains(name),
                            sensitive: schema
                                .get("x-lenso-sensitive")
                                .and_then(Value::as_bool)
                                .unwrap_or(false),
                            ty,
                        }
                    })
                    .collect();
                let additional = match object.get("additionalProperties") {
                    Some(Value::Bool(false)) => ObjectAdditionalIr::Closed,
                    Some(Value::Bool(true)) | None => ObjectAdditionalIr::Any,
                    Some(schema) => {
                        ObjectAdditionalIr::Typed(Box::new(type_ir_from_schema(schema)))
                    }
                };
                TypeIr::Object {
                    name: schema_declared_type_name(object),
                    fields,
                    additional,
                }
            }
            "array" => object.get("items").map_or(TypeIr::Any, |items| {
                TypeIr::Array(Box::new(type_ir_from_schema(items)))
            }),
            "string" => match object.get("format").and_then(Value::as_str) {
                Some("int64") => TypeIr::Int64,
                Some("uint64") => TypeIr::Uint64,
                Some("byte") => TypeIr::Bytes,
                Some("date-time") => TypeIr::Timestamp,
                Some("duration") => TypeIr::Duration,
                _ => TypeIr::String,
            },
            "integer" => TypeIr::Integer,
            "number" => TypeIr::Number,
            "boolean" => TypeIr::Boolean,
            "null" => TypeIr::Null,
            _ => TypeIr::Any,
        };
    }
    TypeIr::Any
}

fn schema_declared_type_name(schema: &Map<String, Value>) -> Option<String> {
    schema
        .get("title")
        .and_then(Value::as_str)
        .filter(|title| !title.is_empty())
        .map(pascal_case)
}

/// A validated, self-contained portable Capability Descriptor.
#[derive(Clone, Debug)]
pub struct Descriptor {
    capability_id: String,
    capability_major: u64,
    version: String,
    digest: String,
    parsed_version: Version,
    portable: bool,
    cross_lane_transfer: bool,
    operations: Vec<Operation>,
}

impl Descriptor {
    /// Returns the stable Capability series identity, including its major.
    #[must_use]
    pub fn capability_id(&self) -> &str {
        &self.capability_id
    }

    /// Returns the major encoded in the Capability identity.
    #[must_use]
    pub const fn capability_major(&self) -> u64 {
        self.capability_major
    }

    /// Returns the exact Descriptor `SemVer` selected for generation.
    #[must_use]
    pub fn version(&self) -> &str {
        &self.version
    }

    /// Returns the canonical digest of the resolved Descriptor and Schemas.
    #[must_use]
    pub fn descriptor_digest(&self) -> &str {
        &self.digest
    }

    /// Returns whether the Capability is intended to cross Runtime Adapters.
    #[must_use]
    pub const fn portable(&self) -> bool {
        self.portable
    }

    /// Returns whether generated native values support transfer across Execution Lanes.
    #[must_use]
    pub const fn cross_lane_transfer(&self) -> bool {
        self.cross_lane_transfer
    }

    /// Returns the stable Operation names in deterministic lexical order.
    #[must_use]
    pub fn operation_names(&self) -> Vec<&str> {
        self.operations
            .iter()
            .map(|operation| operation.name.as_str())
            .collect()
    }
}

/// Metadata embedded in every generated language artifact.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct GeneratedMetadata {
    /// Stable `namespace.name@major` identity.
    pub capability_id: String,
    /// Exact Descriptor `SemVer`.
    pub descriptor_version: String,
    /// Canonical SHA-256 digest of the resolved Descriptor and Schemas.
    pub descriptor_digest: String,
    /// Whether the source Descriptor is portable.
    pub portable: bool,
    /// Whether generated native values may transfer across Execution Lanes.
    pub cross_lane_transfer: bool,
}

/// One language projection emitted from a portable Capability contract.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum ProjectionLanguage {
    /// Native Rust value, consumer, and provider bindings.
    Rust,
    /// TypeScript value, consumer, and provider bindings.
    TypeScript,
    /// WebAssembly Component Model WIT provider and consumer worlds.
    Wit,
    /// Rust bindings plus the generated byte-Adapter Capability codec.
    RustRuntime,
    /// Portable Rust values and a typed Process Plugin dependency client.
    RustPlugin,
}

/// One independently generated language projection.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct GeneratedProjection {
    /// Metadata embedded in the generated projection.
    pub metadata: GeneratedMetadata,
    /// Selected target language.
    pub language: ProjectionLanguage,
    /// Generated provider, client, value, and error bindings.
    pub source: String,
}

/// Compatibility aggregate for callers that intentionally generate both projections.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct GeneratedArtifacts {
    /// Metadata shared by all generated languages.
    pub metadata: GeneratedMetadata,
    /// Rust provider, client, value, and error bindings.
    pub rust: String,
    /// TypeScript provider, client, value, and error bindings.
    pub typescript: String,
}

/// Errors produced while parsing, validating, or generating a contract.
#[derive(Debug)]
pub enum CodegenError {
    /// A file could not be read.
    Io {
        path: PathBuf,
        source: std::io::Error,
    },
    /// Descriptor or Schema data is malformed.
    InvalidDescriptor { detail: String },
    /// A Schema cannot be used by the portable value profile.
    UnsupportedSchema { path: PathBuf, detail: String },
    /// A Descriptor interaction is not supported by the generated language bindings.
    UnsupportedInteraction {
        operation: String,
        interaction: String,
    },
    /// A portable JSON Schema shape has no exact Component Model representation.
    UnsupportedWit { detail: String },
    /// A JSON value would be lossy when represented by JavaScript numbers.
    InvalidPortableValue { path: String, detail: String },
    /// A checked-in generated artifact differs from its source.
    GeneratedArtifactDrift { path: PathBuf },
}

impl fmt::Display for CodegenError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Io { path, source } => write!(formatter, "{}: {source}", path.display()),
            Self::InvalidDescriptor { detail } => {
                write!(formatter, "invalid Descriptor: {detail}")
            }
            Self::UnsupportedSchema { path, detail } => {
                write!(formatter, "unsupported Schema {}: {detail}", path.display())
            }
            Self::UnsupportedInteraction {
                operation,
                interaction,
            } => write!(
                formatter,
                "Operation `{operation}` uses unsupported interaction `{interaction}`"
            ),
            Self::UnsupportedWit { detail } => {
                write!(formatter, "unsupported WIT projection: {detail}")
            }
            Self::InvalidPortableValue { path, detail } => {
                write!(formatter, "invalid portable value at `{path}`: {detail}")
            }
            Self::GeneratedArtifactDrift { path } => {
                write!(formatter, "generated artifact is stale: {}", path.display())
            }
        }
    }
}

impl Error for CodegenError {
    fn source(&self) -> Option<&(dyn Error + 'static)> {
        match self {
            Self::Io { source, .. } => Some(source),
            _ => None,
        }
    }
}

/// Reasons why a Descriptor evolution is not safe for an existing Capability
/// series.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum CompatibilityError {
    /// The two files do not describe the same Capability series.
    IdentityChanged { from: String, to: String },
    /// The new Descriptor is not newer than the old one.
    VersionNotAdvanced { from: String, to: String },
    /// The change is not allowed by the old series and requires a new major.
    BreakingChanges { changes: Vec<String> },
}

impl fmt::Display for CompatibilityError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::IdentityChanged { from, to } => {
                write!(
                    formatter,
                    "Capability identity changed from `{from}` to `{to}`"
                )
            }
            Self::VersionNotAdvanced { from, to } => {
                write!(
                    formatter,
                    "Descriptor version must advance from `{from}` to `{to}`"
                )
            }
            Self::BreakingChanges { changes } => write!(
                formatter,
                "breaking Descriptor changes require a new major: {}",
                changes.join("; ")
            ),
        }
    }
}

impl Error for CompatibilityError {}

/// Reads and validates one Descriptor, resolving package-local `$ref` files.
#[allow(clippy::too_many_lines)]
pub fn load_descriptor(path: &Path) -> Result<Descriptor, CodegenError> {
    let descriptor_path = canonical_path(path)?;
    let package_root = descriptor_path
        .parent()
        .unwrap_or_else(|| Path::new("."))
        .to_path_buf();
    let descriptor_value = read_json(&descriptor_path)?;
    let object = descriptor_value
        .as_object()
        .ok_or_else(|| CodegenError::InvalidDescriptor {
            detail: "the Descriptor root must be an object".to_owned(),
        })?;

    let capability_id = required_string(object, "id")?;
    let (identity, identity_major) = capability_identity(&capability_id)?;
    let version = required_string(object, "version")?;
    let parsed_version = Version::parse(&version)?;
    let portable = object
        .get("portable")
        .and_then(Value::as_bool)
        .unwrap_or(false);
    let cross_lane_transfer = object
        .get("cross_lane_transfer")
        .and_then(Value::as_bool)
        .unwrap_or(false);
    let operation_values = object
        .get("operations")
        .and_then(Value::as_array)
        .ok_or_else(|| CodegenError::InvalidDescriptor {
            detail: "`operations` must be an array".to_owned(),
        })?;
    if operation_values.is_empty() {
        return Err(CodegenError::InvalidDescriptor {
            detail: "a Descriptor must declare at least one Operation".to_owned(),
        });
    }

    let mut operations = Vec::with_capacity(operation_values.len());
    let mut operation_names = BTreeSet::new();
    let mut generated_operation_names = BTreeSet::new();
    let mut generated_type_names = BTreeSet::new();
    let mut generated_client_method_names = BTreeSet::from([
        "new".to_owned(),
        "from_context".to_owned(),
        "from_dependencies".to_owned(),
    ]);
    let capability_name = identity
        .rsplit('.')
        .next()
        .map_or_else(|| "Capability".to_owned(), pascal_case);
    for operation_value in operation_values {
        let operation =
            operation_value
                .as_object()
                .ok_or_else(|| CodegenError::InvalidDescriptor {
                    detail: "each Operation must be an object".to_owned(),
                })?;
        let name = required_string(operation, "name")?;
        if !is_identifier(&name) || !is_rust_member_name(&name) {
            return Err(CodegenError::InvalidDescriptor {
                detail: format!(
                    "Operation name `{name}` must start with a letter or `_` and contain only letters, digits, `_`, or `-`"
                ),
            });
        }
        if !operation_names.insert(name.clone()) {
            return Err(CodegenError::InvalidDescriptor {
                detail: format!("Operation `{name}` is declared more than once"),
            });
        }
        for generated_name in [rust_field_name(&name), pascal_case(&name)] {
            if !generated_operation_names.insert(generated_name.clone()) {
                return Err(CodegenError::InvalidDescriptor {
                    detail: format!(
                        "Operation name `{name}` collides after code generation as `{generated_name}`"
                    ),
                });
            }
        }
        let operation_name = pascal_case(&name);
        let mut generated_names = vec![
            format!("{operation_name}Request"),
            format!("{operation_name}Response"),
            format!("{operation_name}Error"),
            format!("{operation_name}InvocationError"),
            format!("{operation_name}Result"),
            format!("{capability_name}{operation_name}"),
        ];
        generated_names.push(if operation_values.len() == 1 {
            format!("{capability_name}InvocationError")
        } else {
            format!("{capability_name}{operation_name}InvocationError")
        });
        for generated_name in generated_names {
            if !is_generated_type_name(&generated_name)
                || !generated_type_names.insert(generated_name.clone())
            {
                return Err(CodegenError::InvalidDescriptor {
                    detail: format!(
                        "Operation name `{name}` collides after type generation as `{generated_name}`"
                    ),
                });
            }
        }
        let interaction = required_string(operation, "interaction")?;
        if !matches!(interaction.as_str(), "request" | "stream" | "event") {
            return Err(CodegenError::InvalidDescriptor {
                detail: format!("Operation `{name}` has unsupported interaction `{interaction}`"),
            });
        }
        if matches!(interaction.as_str(), "request" | "stream" | "event") {
            let client_method_name = rust_field_name(&name);
            for generated_name in [
                client_method_name.clone(),
                format!("{client_method_name}_with_context"),
            ] {
                if !generated_client_method_names.insert(generated_name.clone()) {
                    return Err(CodegenError::InvalidDescriptor {
                        detail: format!(
                            "Operation name `{name}` collides with the generated Client API as `{generated_name}`"
                        ),
                    });
                }
            }
        }
        let request_schema_path =
            schema_path(&descriptor_path, operation, "request_schema", &name)?;
        let response_schema_path =
            schema_path(&descriptor_path, operation, "response_schema", &name)?;
        let domain_error_schema_path =
            schema_path(&descriptor_path, operation, "domain_error_schema", &name)?;
        let mut ref_stack = Vec::new();
        let request_source = read_json(&request_schema_path)?;
        let mut request_schema = resolve_refs(
            &request_source,
            &request_source,
            &request_schema_path,
            &package_root,
            &mut ref_stack,
        )?;
        normalize_nullable_unions(&mut request_schema);
        validate_schema_profile(&request_schema, &request_schema_path)?;
        validate_value_generation_schema(&request_schema, &request_schema_path)?;
        let mut ref_stack = Vec::new();
        let response_source = read_json(&response_schema_path)?;
        let mut response_schema = resolve_refs(
            &response_source,
            &response_source,
            &response_schema_path,
            &package_root,
            &mut ref_stack,
        )?;
        normalize_nullable_unions(&mut response_schema);
        validate_schema_profile(&response_schema, &response_schema_path)?;
        validate_value_generation_schema(&response_schema, &response_schema_path)?;
        let mut ref_stack = Vec::new();
        let domain_error_source = read_json(&domain_error_schema_path)?;
        let mut domain_error_schema = resolve_refs(
            &domain_error_source,
            &domain_error_source,
            &domain_error_schema_path,
            &package_root,
            &mut ref_stack,
        )?;
        normalize_nullable_unions(&mut domain_error_schema);
        validate_schema_profile(&domain_error_schema, &domain_error_schema_path)?;
        validate_domain_error_schema(&domain_error_schema, &domain_error_schema_path)?;
        operations.push(Operation {
            name,
            interaction,
            request_schema,
            response_schema,
            domain_error_schema,
        });
    }
    operations.sort_by(|left, right| left.name.cmp(&right.name));

    let capability_id = format!("{identity}@{identity_major}");
    let descriptor_digest = resolved_descriptor_digest(
        &capability_id,
        &version,
        portable,
        cross_lane_transfer,
        &operations,
    );
    Ok(Descriptor {
        capability_id,
        capability_major: identity_major,
        version,
        digest: descriptor_digest,
        parsed_version,
        portable,
        cross_lane_transfer,
        operations,
    })
}

fn resolved_descriptor_digest(
    capability_id: &str,
    version: &str,
    portable: bool,
    cross_lane_transfer: bool,
    operations: &[Operation],
) -> String {
    let operations = operations
        .iter()
        .map(|operation| {
            serde_json::json!({
                "name": operation.name,
                "interaction": operation.interaction,
                "request_schema": operation.request_schema,
                "response_schema": operation.response_schema,
                "domain_error_schema": operation.domain_error_schema,
            })
        })
        .collect::<Vec<_>>();
    let value = serde_json::json!({
        "capability_id": capability_id,
        "version": version,
        "portable": portable,
        "cross_lane_transfer": cross_lane_transfer,
        "operations": operations,
    });
    let canonical = canonicalize_json(&value);
    format!("sha256:{:x}", Sha256::digest(canonical.as_bytes()))
}

fn canonicalize_json(value: &Value) -> String {
    match value {
        Value::Array(values) => format!(
            "[{}]",
            values
                .iter()
                .map(canonicalize_json)
                .collect::<Vec<_>>()
                .join(",")
        ),
        Value::Object(object) => {
            let mut keys = object.keys().collect::<Vec<_>>();
            keys.sort();
            format!(
                "{{{}}}",
                keys.into_iter()
                    .map(|key| format!(
                        "{}:{}",
                        serde_json::to_string(key).expect("object keys serialize"),
                        canonicalize_json(&object[key])
                    ))
                    .collect::<Vec<_>>()
                    .join(",")
            )
        }
        _ => serde_json::to_string(value).expect("JSON values serialize"),
    }
}

fn required_string(object: &Map<String, Value>, key: &str) -> Result<String, CodegenError> {
    object
        .get(key)
        .and_then(Value::as_str)
        .filter(|value| !value.is_empty())
        .map(ToOwned::to_owned)
        .ok_or_else(|| CodegenError::InvalidDescriptor {
            detail: format!("`{key}` must be a non-empty string"),
        })
}

fn capability_identity(value: &str) -> Result<(String, u64), CodegenError> {
    let Some((identity, major)) = value.rsplit_once('@') else {
        return Err(CodegenError::InvalidDescriptor {
            detail: format!("Capability id `{value}` must use `namespace.name@major`"),
        });
    };
    let generated_name = identity
        .rsplit('.')
        .next()
        .map(pascal_case)
        .unwrap_or_default();
    if identity.is_empty()
        || identity.split('.').count() < 2
        || !identity.split('.').all(is_identifier)
        || !is_generated_type_name(&generated_name)
    {
        return Err(CodegenError::InvalidDescriptor {
            detail: format!("Capability id `{value}` must use `namespace.name@major`"),
        });
    }
    let Some(major) = parse_numeric_component(major) else {
        return Err(CodegenError::InvalidDescriptor {
            detail: format!("Capability id `{value}` has an invalid major"),
        });
    };
    Ok((identity.to_owned(), major))
}

fn schema_path(
    descriptor_path: &Path,
    operation: &Map<String, Value>,
    key: &str,
    operation_name: &str,
) -> Result<PathBuf, CodegenError> {
    let value = required_string(operation, key).map_err(|error| match error {
        CodegenError::InvalidDescriptor { detail } => CodegenError::InvalidDescriptor {
            detail: format!("Operation `{operation_name}`: {detail}"),
        },
        other => other,
    })?;
    let candidate = descriptor_path
        .parent()
        .unwrap_or_else(|| Path::new("."))
        .join(value);
    let canonical = canonical_path(&candidate)?;
    let package_root = canonical_path(descriptor_path.parent().unwrap_or_else(|| Path::new(".")))?;
    if !canonical.starts_with(&package_root) {
        return Err(CodegenError::UnsupportedSchema {
            path: canonical,
            detail: "Schema paths must remain inside the Descriptor package".to_owned(),
        });
    }
    Ok(canonical)
}

fn canonical_path(path: &Path) -> Result<PathBuf, CodegenError> {
    fs::canonicalize(path).map_err(|source| CodegenError::Io {
        path: path.to_path_buf(),
        source,
    })
}

fn read_json(path: &Path) -> Result<Value, CodegenError> {
    let source = fs::read_to_string(path).map_err(|source| CodegenError::Io {
        path: path.to_path_buf(),
        source,
    })?;
    serde_json::from_str(&source).map_err(|error| CodegenError::InvalidDescriptor {
        detail: format!("{}: {error}", path.display()),
    })
}

fn resolve_refs(
    value: &Value,
    root: &Value,
    source_path: &Path,
    package_root: &Path,
    stack: &mut Vec<(PathBuf, String)>,
) -> Result<Value, CodegenError> {
    match value {
        Value::Object(object) => {
            if let Some(reference) = object.get("$ref").and_then(Value::as_str) {
                let target_value = if reference.starts_with('#') {
                    let fragment = reference.strip_prefix('#').unwrap_or_default();
                    let target_path = source_path.to_path_buf();
                    let key = (target_path.clone(), reference.to_owned());
                    if stack.contains(&key) {
                        return Err(CodegenError::UnsupportedSchema {
                            path: source_path.to_path_buf(),
                            detail: format!("cyclic local Schema `$ref` `{reference}`"),
                        });
                    }
                    let target = json_pointer(root, fragment).ok_or_else(|| {
                        CodegenError::UnsupportedSchema {
                            path: source_path.to_path_buf(),
                            detail: format!(
                                "local JSON Pointer `$ref` `{reference}` was not found"
                            ),
                        }
                    })?;
                    stack.push(key);
                    let resolved = resolve_refs(target, root, source_path, package_root, stack)?;
                    stack.pop();
                    resolved
                } else {
                    let (reference_path, fragment) =
                        reference.split_once('#').unwrap_or((reference, ""));
                    let target_path = source_path
                        .parent()
                        .unwrap_or_else(|| Path::new("."))
                        .join(reference_path);
                    let target_path = canonical_path(&target_path)?;
                    if !target_path.starts_with(package_root) {
                        return Err(CodegenError::UnsupportedSchema {
                            path: source_path.to_path_buf(),
                            detail: format!(
                                "external Schema `$ref` `{reference}` leaves the Descriptor package"
                            ),
                        });
                    }
                    let key = (target_path.clone(), format!("#{fragment}"));
                    if stack.contains(&key) {
                        return Err(CodegenError::UnsupportedSchema {
                            path: source_path.to_path_buf(),
                            detail: format!(
                                "cyclic Schema `$ref` through {}",
                                target_path.display()
                            ),
                        });
                    }
                    let target_root = read_json(&target_path)?;
                    let target = json_pointer(&target_root, fragment).ok_or_else(|| {
                        CodegenError::UnsupportedSchema {
                            path: source_path.to_path_buf(),
                            detail: format!(
                                "external JSON Pointer `$ref` `{reference}` was not found"
                            ),
                        }
                    })?;
                    stack.push(key);
                    let resolved =
                        resolve_refs(target, &target_root, &target_path, package_root, stack)?;
                    stack.pop();
                    resolved
                };
                let mut merged = target_value.as_object().cloned().ok_or_else(|| {
                    CodegenError::UnsupportedSchema {
                        path: source_path.to_path_buf(),
                        detail: "a `$ref` target must resolve to an object Schema".to_owned(),
                    }
                })?;
                restore_reference_type_name(&mut merged, reference);
                for (key, child) in object {
                    if key != "$ref" {
                        merged.insert(
                            key.clone(),
                            resolve_refs(child, root, source_path, package_root, stack)?,
                        );
                    }
                }
                return Ok(Value::Object(merged));
            }
            let mut resolved = Map::new();
            for (key, child) in object {
                resolved.insert(
                    key.clone(),
                    resolve_refs(child, root, source_path, package_root, stack)?,
                );
            }
            Ok(Value::Object(resolved))
        }
        Value::Array(values) => values
            .iter()
            .map(|child| resolve_refs(child, root, source_path, package_root, stack))
            .collect::<Result<Vec<_>, _>>()
            .map(Value::Array),
        _ => Ok(value.clone()),
    }
}

fn reference_definition_name(reference: &str) -> Option<String> {
    let (_, fragment) = reference.rsplit_once('#')?;
    let name = fragment.strip_prefix("/$defs/")?;
    if name.is_empty() || name.contains('/') {
        return None;
    }
    Some(name.replace("~1", "/").replace("~0", "~"))
}

fn restore_reference_type_name(schema: &mut Map<String, Value>, reference: &str) {
    if schema.get("title").is_none()
        && let Some(name) = reference_definition_name(reference)
    {
        schema.insert("title".to_owned(), Value::String(name));
    }
}

fn json_pointer<'a>(root: &'a Value, fragment: &str) -> Option<&'a Value> {
    if fragment.is_empty() {
        return Some(root);
    }
    let pointer = fragment.strip_prefix('/')?;
    let mut current = root;
    for token in pointer.split('/') {
        let token = token.replace("~1", "/").replace("~0", "~");
        current = match current {
            Value::Object(object) => object.get(&token)?,
            Value::Array(array) => array.get(token.parse::<usize>().ok()?)?,
            _ => return None,
        };
    }
    Some(current)
}

fn normalize_nullable_unions(value: &mut Value) {
    match value {
        Value::Object(object) => {
            for child in object.values_mut() {
                normalize_nullable_unions(child);
            }
            let nullable = ["anyOf", "oneOf"].into_iter().find_map(|key| {
                let alternatives = object.get(key)?.as_array()?;
                if alternatives.len() != 2 {
                    return None;
                }
                let null_index = alternatives.iter().position(|alternative| {
                    alternative.get("type").and_then(Value::as_str) == Some("null")
                })?;
                let non_null = alternatives.get(1 - null_index)?.as_object()?.clone();
                let schema_type = non_null
                    .get("type")
                    .and_then(Value::as_str)
                    .map(ToOwned::to_owned)?;
                Some((key, schema_type, non_null))
            });
            if let Some((union_key, schema_type, mut normalized)) = nullable {
                normalized.insert(
                    "type".to_owned(),
                    Value::Array(vec![
                        Value::String(schema_type),
                        Value::String("null".to_owned()),
                    ]),
                );
                for (key, child) in std::mem::take(object) {
                    if key != union_key {
                        normalized.entry(key).or_insert(child);
                    }
                }
                *object = normalized;
            }
        }
        Value::Array(values) => {
            for child in values {
                normalize_nullable_unions(child);
            }
        }
        _ => {}
    }
}

const SUPPORTED_SCHEMA_KEYWORDS: &[&str] = &[
    "$defs",
    "additionalProperties",
    "anyOf",
    "const",
    "else",
    "enum",
    "exclusiveMaximum",
    "exclusiveMinimum",
    "format",
    "if",
    "items",
    "maxItems",
    "maxLength",
    "maxProperties",
    "maximum",
    "minItems",
    "minLength",
    "minProperties",
    "minimum",
    "oneOf",
    "pattern",
    "properties",
    "propertyNames",
    "required",
    "then",
    "type",
    "uniqueItems",
];

const HARMLESS_SCHEMA_ANNOTATIONS: &[&str] = &[
    "$anchor",
    "$comment",
    "$dynamicAnchor",
    "$id",
    "$schema",
    "default",
    "deprecated",
    "description",
    "examples",
    "readOnly",
    "title",
    "writeOnly",
    "x-lenso-max-container-items",
    "x-lenso-max-depth",
    "x-lenso-max-encoded-bytes",
    "x-lenso-max-nodes",
    "x-lenso-max-string-length",
    "x-lenso-sensitive",
];

const PORTABLE_SCHEMA_TYPES: &[&str] = &[
    "array", "boolean", "integer", "null", "number", "object", "string",
];

const PORTABLE_STRING_FORMATS: &[&str] = &["byte", "date-time", "duration", "int64", "uint64"];
const MAX_PORTABLE_PATTERN_CHARS: usize = 4_096;
const MAX_PORTABLE_REPETITION: u32 = 10_000;
const PORTABLE_UNICODE_PROPERTY_ESCAPE: &str = r"\p{Letter}";

fn validate_schema_profile(schema: &Value, source_path: &Path) -> Result<(), CodegenError> {
    let Some(object) = schema.as_object() else {
        return Err(unsupported_schema(
            source_path,
            "a JSON Schema must be an object",
        ));
    };

    for keyword in object.keys() {
        if !SUPPORTED_SCHEMA_KEYWORDS.contains(&keyword.as_str())
            && !HARMLESS_SCHEMA_ANNOTATIONS.contains(&keyword.as_str())
        {
            return Err(unsupported_schema(
                source_path,
                format!("Schema keyword `{keyword}` is outside the portable profile"),
            ));
        }
    }

    validate_schema_type_keyword(object, source_path)?;
    validate_schema_composition_keywords(object, source_path)?;
    validate_schema_scalar_keywords(object, source_path)?;
    validate_schema_numeric_keywords(object, source_path)?;
    validate_schema_children(object, source_path)
}

fn validate_schema_type_keyword(
    object: &Map<String, Value>,
    source_path: &Path,
) -> Result<(), CodegenError> {
    if let Some(schema_type) = object.get("type") {
        match schema_type {
            Value::String(schema_type) => validate_schema_type(schema_type, source_path)?,
            Value::Array(types) if !types.is_empty() => {
                let mut unique = BTreeSet::new();
                for schema_type in types {
                    let Some(schema_type) = schema_type.as_str() else {
                        return Err(unsupported_schema(
                            source_path,
                            "Schema type unions must contain strings",
                        ));
                    };
                    validate_schema_type(schema_type, source_path)?;
                    if !unique.insert(schema_type) {
                        return Err(unsupported_schema(
                            source_path,
                            "Schema type unions must be unique",
                        ));
                    }
                }
            }
            Value::Array(_) => {
                return Err(unsupported_schema(
                    source_path,
                    "a Schema type union cannot be empty",
                ));
            }
            _ => {
                return Err(unsupported_schema(
                    source_path,
                    "Schema `type` must be a string or array",
                ));
            }
        }
    }

    Ok(())
}

fn validate_schema_composition_keywords(
    object: &Map<String, Value>,
    source_path: &Path,
) -> Result<(), CodegenError> {
    for keyword in ["oneOf", "anyOf"] {
        if let Some(value) = object.get(keyword) {
            let Some(alternatives) = value.as_array().filter(|values| !values.is_empty()) else {
                return Err(unsupported_schema(
                    source_path,
                    format!("Schema `{keyword}` must be a non-empty array of Schemas"),
                ));
            };
            for alternative in alternatives {
                validate_schema_profile(alternative, source_path)?;
            }
        }
    }

    Ok(())
}

fn validate_schema_scalar_keywords(
    object: &Map<String, Value>,
    source_path: &Path,
) -> Result<(), CodegenError> {
    if let Some(values) = object.get("enum")
        && values.as_array().is_none_or(Vec::is_empty)
    {
        return Err(unsupported_schema(
            source_path,
            "Schema `enum` must be a non-empty array",
        ));
    }
    if let Some(required) = object.get("required")
        && required
            .as_array()
            .is_none_or(|values| values.iter().any(|value| !value.is_string()))
    {
        return Err(unsupported_schema(
            source_path,
            "Schema `required` must be an array of strings",
        ));
    }
    if let Some(pattern) = object.get("pattern") {
        let Some(pattern) = pattern.as_str() else {
            return Err(unsupported_schema(
                source_path,
                "Schema `pattern` must be a string",
            ));
        };
        compile_portable_pattern(pattern).map_err(|error| {
            unsupported_schema(
                source_path,
                format!("Schema `pattern` is outside the portable regex subset: {error}"),
            )
        })?;
    }
    if let Some(format) = object.get("format") {
        let Some(format) = format.as_str() else {
            return Err(unsupported_schema(
                source_path,
                "Schema `format` must be a string",
            ));
        };
        if !PORTABLE_STRING_FORMATS.contains(&format) {
            return Err(unsupported_schema(
                source_path,
                format!("format `{format}` is outside the portable value profile"),
            ));
        }
    }
    if object
        .get("uniqueItems")
        .is_some_and(|value| !value.is_boolean())
    {
        return Err(unsupported_schema(
            source_path,
            "Schema `uniqueItems` must be a boolean",
        ));
    }

    Ok(())
}

fn validate_schema_numeric_keywords(
    object: &Map<String, Value>,
    source_path: &Path,
) -> Result<(), CodegenError> {
    for keyword in [
        "minLength",
        "maxLength",
        "minItems",
        "maxItems",
        "minProperties",
        "maxProperties",
    ] {
        if let Some(value) = object.get(keyword)
            && non_negative_safe_schema_integer(value).is_none()
        {
            return Err(unsupported_schema(
                source_path,
                format!("Schema `{keyword}` must be a non-negative safe integer"),
            ));
        }
    }
    for keyword in ["minimum", "maximum", "exclusiveMinimum", "exclusiveMaximum"] {
        if let Some(value) = object.get(keyword)
            && value.as_f64().is_none_or(|number| !number.is_finite())
        {
            return Err(unsupported_schema(
                source_path,
                format!("Schema `{keyword}` must be a finite number"),
            ));
        }
    }

    Ok(())
}

fn validate_schema_children(
    object: &Map<String, Value>,
    source_path: &Path,
) -> Result<(), CodegenError> {
    if let Some(items) = object.get("items") {
        validate_schema_profile(items, source_path)?;
    }
    for keyword in ["properties", "$defs"] {
        if let Some(value) = object.get(keyword) {
            let Some(schemas) = value.as_object() else {
                return Err(unsupported_schema(
                    source_path,
                    format!("Schema `{keyword}` must be an object of Schemas"),
                ));
            };
            for child in schemas.values() {
                validate_schema_profile(child, source_path)?;
            }
        }
    }
    if let Some(additional) = object.get("additionalProperties")
        && !additional.is_boolean()
    {
        validate_schema_profile(additional, source_path)?;
    }
    if let Some(property_names) = object.get("propertyNames") {
        validate_schema_profile(property_names, source_path)?;
    }
    if object.contains_key("then") || object.contains_key("else") {
        let Some(condition) = object.get("if") else {
            return Err(unsupported_schema(
                source_path,
                "Schema `then` and `else` require an `if` Schema",
            ));
        };
        validate_schema_profile(condition, source_path)?;
    } else if let Some(condition) = object.get("if") {
        validate_schema_profile(condition, source_path)?;
    }
    for keyword in ["then", "else"] {
        if let Some(branch) = object.get(keyword) {
            validate_schema_profile(branch, source_path)?;
        }
    }

    Ok(())
}

fn validate_schema_type(schema_type: &str, source_path: &Path) -> Result<(), CodegenError> {
    if PORTABLE_SCHEMA_TYPES.contains(&schema_type) {
        Ok(())
    } else {
        Err(unsupported_schema(
            source_path,
            format!("Schema type `{schema_type}` is outside the portable profile"),
        ))
    }
}

/// Compiles only the regular-expression syntax whose match semantics are shared
/// by Rust `regex` and ECMAScript Unicode-mode `RegExp` for portable Schemas.
/// Engine-specific shorthand classes, internal anchors, wildcard dots,
/// lookarounds, backreferences, inline flags, and backtracking-unsafe
/// repetition shapes fail closed before either runtime uses them. Fully
/// anchored patterns may use the complete safe subset; start-anchored prefix
/// patterns are limited to fixed-shape expressions.
fn compile_portable_pattern(pattern: &str) -> Result<Regex, String> {
    if !has_portable_pattern_syntax(pattern) {
        return Err("pattern uses syntax outside the shared Rust/ECMAScript subset".to_owned());
    }
    Regex::new(pattern).map_err(|error| error.to_string())
}

#[derive(Clone, Copy, Debug, Default)]
#[expect(
    clippy::struct_excessive_bools,
    reason = "these are independent regex risk facts mirrored explicitly in the TypeScript gate"
)]
struct PortablePatternAtom {
    can_match_empty: bool,
    has_variable_shape: bool,
    is_quantified: bool,
    prefix_can_match_empty: bool,
    contains_variable_repetition: bool,
    contains_alternation: bool,
    is_group: bool,
}

#[derive(Debug)]
#[expect(
    clippy::struct_excessive_bools,
    reason = "branch-local and group-wide regex risk facts are independent parser state"
)]
struct PortablePatternFrame {
    sequence_can_match_empty: bool,
    earlier_branch_can_match_empty: bool,
    contains_variable_repetition: bool,
    contains_alternation: bool,
    branch_has_variable_shape: bool,
    last_atom: Option<PortablePatternAtom>,
}

impl Default for PortablePatternFrame {
    fn default() -> Self {
        Self {
            sequence_can_match_empty: true,
            earlier_branch_can_match_empty: false,
            contains_variable_repetition: false,
            contains_alternation: false,
            branch_has_variable_shape: false,
            last_atom: None,
        }
    }
}

#[derive(Clone, Copy, Debug)]
struct PortableRepetition {
    minimum: u32,
    maximum: Option<u32>,
}

impl PortableRepetition {
    fn has_variable_extent(self) -> bool {
        self.maximum != Some(self.minimum)
    }
}

#[expect(
    clippy::too_many_lines,
    reason = "keeping the single-pass scanner locally isomorphic with the TypeScript gate makes parity auditable"
)]
fn has_portable_pattern_syntax(pattern: &str) -> bool {
    if pattern.chars().count() > MAX_PORTABLE_PATTERN_CHARS
        || pattern.as_bytes().first() != Some(&b'^')
    {
        return false;
    }

    let bytes = pattern.as_bytes();
    let mut index = 0;
    let mut in_class = false;
    let mut class_start = None;
    let mut frames = vec![PortablePatternFrame::default()];
    while index < bytes.len() {
        if in_class {
            match bytes[index] {
                b'\\' => {
                    if pattern[index..].starts_with(PORTABLE_UNICODE_PROPERTY_ESCAPE) {
                        index += PORTABLE_UNICODE_PROPERTY_ESCAPE.len();
                        continue;
                    }
                    let Some(&escaped) = bytes.get(index + 1) else {
                        return false;
                    };
                    if !matches!(
                        escaped,
                        b'^' | b'$'
                            | b'\\'
                            | b'.'
                            | b'*'
                            | b'+'
                            | b'?'
                            | b'('
                            | b')'
                            | b'['
                            | b']'
                            | b'{'
                            | b'}'
                            | b'|'
                            | b'/'
                            | b'-'
                    ) {
                        return false;
                    }
                    index += 2;
                }
                b']' => {
                    let Some(start) = class_start.take() else {
                        return false;
                    };
                    if matches!(&pattern[start..index], "" | "^") {
                        return false;
                    }
                    in_class = false;
                    let Some(frame) = frames.last_mut() else {
                        return false;
                    };
                    if !push_portable_pattern_atom(frame, PortablePatternAtom::default()) {
                        return false;
                    }
                    index += 1;
                }
                b'[' => return false,
                operator @ (b'&' | b'-' | b'~' | b'|')
                    if bytes.get(index + 1) == Some(&operator) =>
                {
                    return false;
                }
                byte if byte.is_ascii_control() => return false,
                byte if byte.is_ascii() => index += 1,
                _ => {
                    let Some(character) = pattern[index..].chars().next() else {
                        return false;
                    };
                    if character.is_control() {
                        return false;
                    }
                    index += character.len_utf8();
                }
            }
            continue;
        }

        match bytes[index] {
            b'\\' => {
                if pattern[index..].starts_with(PORTABLE_UNICODE_PROPERTY_ESCAPE) {
                    index += PORTABLE_UNICODE_PROPERTY_ESCAPE.len();
                } else {
                    let Some(&escaped) = bytes.get(index + 1) else {
                        return false;
                    };
                    if !matches!(
                        escaped,
                        b'^' | b'$'
                            | b'\\'
                            | b'.'
                            | b'*'
                            | b'+'
                            | b'?'
                            | b'('
                            | b')'
                            | b'['
                            | b']'
                            | b'{'
                            | b'}'
                            | b'|'
                            | b'/'
                    ) {
                        return false;
                    }
                    index += 2;
                }
                let Some(frame) = frames.last_mut() else {
                    return false;
                };
                if !push_portable_pattern_atom(frame, PortablePatternAtom::default()) {
                    return false;
                }
            }
            b'[' => {
                in_class = true;
                class_start = Some(index + 1);
                index += 1;
            }
            b'(' => {
                if bytes.get(index + 1) == Some(&b'?') {
                    if !pattern[index..].starts_with("(?:") {
                        return false;
                    }
                    index += 3;
                } else {
                    index += 1;
                }
                frames.push(PortablePatternFrame::default());
            }
            b')' => {
                if frames.len() == 1 {
                    return false;
                }
                let Some(group) = frames.pop() else {
                    return false;
                };
                let can_match_empty =
                    group.earlier_branch_can_match_empty || group.sequence_can_match_empty;
                if can_match_empty {
                    return false;
                }
                let atom = PortablePatternAtom {
                    can_match_empty,
                    has_variable_shape: group.contains_variable_repetition
                        || group.contains_alternation,
                    contains_variable_repetition: group.contains_variable_repetition,
                    contains_alternation: group.contains_alternation,
                    is_group: true,
                    ..PortablePatternAtom::default()
                };
                let Some(parent) = frames.last_mut() else {
                    return false;
                };
                if !push_portable_pattern_atom(parent, atom) {
                    return false;
                }
                index += 1;
            }
            b'|' => {
                if frames.len() == 1 {
                    return false;
                }
                let Some(frame) = frames.last_mut() else {
                    return false;
                };
                frame.contains_alternation = true;
                frame.earlier_branch_can_match_empty |= frame.sequence_can_match_empty;
                frame.sequence_can_match_empty = true;
                frame.branch_has_variable_shape = false;
                frame.last_atom = None;
                index += 1;
            }
            b'*' | b'+' | b'?' => {
                let repetition = match bytes[index] {
                    b'*' => PortableRepetition {
                        minimum: 0,
                        maximum: None,
                    },
                    b'+' => PortableRepetition {
                        minimum: 1,
                        maximum: None,
                    },
                    b'?' => PortableRepetition {
                        minimum: 0,
                        maximum: Some(1),
                    },
                    _ => unreachable!(),
                };
                let Some(frame) = frames.last_mut() else {
                    return false;
                };
                if !apply_portable_repetition(frame, repetition) {
                    return false;
                }
                index += 1;
            }
            b'{' => {
                let Some(close_offset) = pattern[index + 1..].find('}') else {
                    return false;
                };
                let close = index + 1 + close_offset;
                let Some(repetition) = parse_portable_repetition(&pattern[index + 1..close]) else {
                    return false;
                };
                let Some(frame) = frames.last_mut() else {
                    return false;
                };
                if !apply_portable_repetition(frame, repetition) {
                    return false;
                }
                index = close + 1;
            }
            b'^' if index == 0 => {
                let Some(frame) = frames.last_mut() else {
                    return false;
                };
                frame.last_atom = None;
                index += 1;
            }
            b'$' if is_portable_end_anchor(pattern, index) => {
                let Some(frame) = frames.last_mut() else {
                    return false;
                };
                frame.last_atom = None;
                index += 1;
            }
            b']' | b'}' | b'.' | b'^' | b'$' => return false,
            byte if byte.is_ascii_control() => return false,
            byte if byte.is_ascii() => {
                let Some(frame) = frames.last_mut() else {
                    return false;
                };
                if !push_portable_pattern_atom(frame, PortablePatternAtom::default()) {
                    return false;
                }
                index += 1;
            }
            _ => {
                let Some(character) = pattern[index..].chars().next() else {
                    return false;
                };
                if character.is_control() {
                    return false;
                }
                let Some(frame) = frames.last_mut() else {
                    return false;
                };
                if !push_portable_pattern_atom(frame, PortablePatternAtom::default()) {
                    return false;
                }
                index += character.len_utf8();
            }
        }
    }

    if in_class || frames.len() != 1 {
        return false;
    }
    let frame = &frames[0];
    has_portable_end_anchor(pattern)
        || (frame.last_atom.is_some()
            && !frame.contains_variable_repetition
            && !frame.contains_alternation)
}

fn has_portable_end_anchor(pattern: &str) -> bool {
    let bytes = pattern.as_bytes();
    if bytes.last() != Some(&b'$') {
        return false;
    }
    bytes[..bytes.len() - 1]
        .iter()
        .rev()
        .take_while(|byte| **byte == b'\\')
        .count()
        % 2
        == 0
}

fn is_portable_end_anchor(pattern: &str, index: usize) -> bool {
    index + 1 == pattern.len() && has_portable_end_anchor(pattern)
}

fn push_portable_pattern_atom(
    frame: &mut PortablePatternFrame,
    mut atom: PortablePatternAtom,
) -> bool {
    if atom.has_variable_shape && frame.branch_has_variable_shape {
        return false;
    }
    atom.prefix_can_match_empty = frame.sequence_can_match_empty;
    frame.sequence_can_match_empty &= atom.can_match_empty;
    frame.branch_has_variable_shape |= atom.has_variable_shape;
    frame.contains_variable_repetition |= atom.contains_variable_repetition;
    frame.contains_alternation |= atom.contains_alternation;
    frame.last_atom = Some(atom);
    true
}

fn apply_portable_repetition(
    frame: &mut PortablePatternFrame,
    repetition: PortableRepetition,
) -> bool {
    let Some(atom) = frame.last_atom.as_mut() else {
        return false;
    };
    if atom.is_quantified || repetition.maximum == Some(0) {
        return false;
    }
    if atom.is_group
        && (atom.can_match_empty || atom.contains_variable_repetition || atom.contains_alternation)
    {
        return false;
    }

    let has_variable_extent = repetition.has_variable_extent();
    if has_variable_extent && frame.branch_has_variable_shape {
        return false;
    }
    atom.is_quantified = true;
    atom.has_variable_shape |= has_variable_extent;
    atom.can_match_empty = repetition.minimum == 0 || atom.can_match_empty;
    frame.sequence_can_match_empty = atom.prefix_can_match_empty && atom.can_match_empty;
    frame.branch_has_variable_shape |= has_variable_extent;
    frame.contains_variable_repetition |= has_variable_extent;
    true
}

fn parse_portable_repetition(value: &str) -> Option<PortableRepetition> {
    let (minimum, maximum) = if let Some((minimum, maximum)) = value.split_once(',') {
        if maximum.contains(',') {
            return None;
        }
        let minimum = parse_portable_repetition_bound(minimum)?;
        let maximum = if maximum.is_empty() {
            None
        } else {
            Some(parse_portable_repetition_bound(maximum)?)
        };
        (minimum, maximum)
    } else {
        let minimum = parse_portable_repetition_bound(value)?;
        (minimum, Some(minimum))
    };
    if maximum.is_some_and(|maximum| maximum < minimum) {
        return None;
    }
    Some(PortableRepetition { minimum, maximum })
}

fn parse_portable_repetition_bound(value: &str) -> Option<u32> {
    if value.is_empty()
        || value.len() > 1 && value.starts_with('0')
        || !value.bytes().all(|byte| byte.is_ascii_digit())
    {
        return None;
    }
    value
        .parse::<u32>()
        .ok()
        .filter(|value| *value <= MAX_PORTABLE_REPETITION)
}

#[expect(
    clippy::cast_possible_truncation,
    clippy::cast_sign_loss,
    reason = "the finite, non-negative, integral, safe-integer checks make this conversion exact"
)]
fn non_negative_safe_schema_integer(value: &Value) -> Option<u64> {
    let number = value.as_f64()?;
    (number.is_finite()
        && number >= 0.0
        && number.fract() == 0.0
        && number <= 9_007_199_254_740_991.0)
        .then_some(number as u64)
}

fn unsupported_schema(source_path: &Path, detail: impl Into<String>) -> CodegenError {
    CodegenError::UnsupportedSchema {
        path: source_path.to_path_buf(),
        detail: detail.into(),
    }
}

#[allow(clippy::too_many_lines)]
fn validate_value_generation_schema(
    schema: &Value,
    source_path: &Path,
) -> Result<(), CodegenError> {
    let Some(object) = schema.as_object() else {
        return Err(CodegenError::UnsupportedSchema {
            path: source_path.to_path_buf(),
            detail: "generated value Schemas must be objects".to_owned(),
        });
    };
    if object.contains_key("oneOf") || object.contains_key("anyOf") {
        return Err(CodegenError::UnsupportedSchema {
            path: source_path.to_path_buf(),
            detail: "generated value Schemas do not support oneOf/anyOf unions".to_owned(),
        });
    }
    if object.contains_key("allOf") {
        return Err(CodegenError::UnsupportedSchema {
            path: source_path.to_path_buf(),
            detail: "generated value Schemas do not support allOf unions".to_owned(),
        });
    }
    if object.contains_key("const") {
        return Err(CodegenError::UnsupportedSchema {
            path: source_path.to_path_buf(),
            detail: "generated value Schemas do not support const fields".to_owned(),
        });
    }
    if let Some(types) = object.get("type").and_then(Value::as_array) {
        let non_null = types
            .iter()
            .filter(|schema_type| *schema_type != "null")
            .count();
        if non_null > 1 {
            return Err(CodegenError::UnsupportedSchema {
                path: source_path.to_path_buf(),
                detail: "generated value Schemas only support nullable type unions".to_owned(),
            });
        }
        let mut narrowed = object.clone();
        let Some(schema_type) = types.iter().find(|schema_type| *schema_type != "null") else {
            return Ok(());
        };
        narrowed.insert("type".to_owned(), schema_type.clone());
        return validate_value_generation_schema(&Value::Object(narrowed), source_path);
    }
    if let Some(values) = object.get("enum").and_then(Value::as_array) {
        if values.is_empty() || !values.iter().all(Value::is_string) {
            return Err(CodegenError::UnsupportedSchema {
                path: source_path.to_path_buf(),
                detail: "generated enum values must be non-empty strings".to_owned(),
            });
        }
        let mut enum_names = BTreeSet::new();
        for value in values.iter().filter_map(Value::as_str) {
            let name = pascal_case(value);
            if !is_generated_enum_variant(&name) || !enum_names.insert(name) {
                return Err(CodegenError::UnsupportedSchema {
                    path: source_path.to_path_buf(),
                    detail: "generated enum values collide after Rust variant generation"
                        .to_owned(),
                });
            }
        }
    }
    let Some(schema_type) = object.get("type").and_then(Value::as_str) else {
        if object.contains_key("enum") {
            return Ok(());
        }
        return Err(CodegenError::UnsupportedSchema {
            path: source_path.to_path_buf(),
            detail: "generated value Schemas need a supported type or string enum".to_owned(),
        });
    };
    match schema_type {
        "object" => {
            let properties = object
                .get("properties")
                .and_then(Value::as_object)
                .cloned()
                .unwrap_or_default();
            let mut rust_names = BTreeSet::new();
            let mut nested_type_names = BTreeSet::new();
            for (name, property) in &properties {
                if !rust_names.insert(rust_field_name(name)) {
                    return Err(CodegenError::UnsupportedSchema {
                        path: source_path.to_path_buf(),
                        detail: format!(
                            "object properties collide after Rust field normalization near `{name}`"
                        ),
                    });
                }
                if !nested_type_names.insert(pascal_case(name)) {
                    return Err(CodegenError::UnsupportedSchema {
                        path: source_path.to_path_buf(),
                        detail: format!(
                            "object properties collide after nested type-name generation near `{name}`"
                        ),
                    });
                }
                validate_value_generation_schema(property, source_path)?;
            }
            match object.get("additionalProperties") {
                Some(Value::Bool(false)) => {}
                Some(Value::Bool(true)) | None if !properties.is_empty() => {
                    return Err(CodegenError::UnsupportedSchema {
                        path: source_path.to_path_buf(),
                        detail: "open objects with declared properties would lose unknown fields"
                            .to_owned(),
                    });
                }
                Some(additional) if !additional.is_boolean() && !properties.is_empty() => {
                    return Err(CodegenError::UnsupportedSchema {
                        path: source_path.to_path_buf(),
                        detail: "objects cannot combine declared properties with a map payload"
                            .to_owned(),
                    });
                }
                Some(additional) if !additional.is_boolean() => {
                    validate_value_generation_schema(additional, source_path)?;
                }
                _ => {}
            }
        }
        "array" => {
            let items = object
                .get("items")
                .ok_or_else(|| CodegenError::UnsupportedSchema {
                    path: source_path.to_path_buf(),
                    detail: "generated array Schemas must declare items".to_owned(),
                })?;
            validate_value_generation_schema(items, source_path)?;
        }
        "string" | "integer" | "number" | "boolean" | "null" => {}
        _ => {
            return Err(CodegenError::UnsupportedSchema {
                path: source_path.to_path_buf(),
                detail: format!("Schema type `{schema_type}` cannot be generated"),
            });
        }
    }
    Ok(())
}

fn validate_domain_error_schema(schema: &Value, source_path: &Path) -> Result<(), CodegenError> {
    if schema
        .as_object()
        .is_some_and(|object| object.contains_key("allOf"))
    {
        return Err(CodegenError::UnsupportedSchema {
            path: source_path.to_path_buf(),
            detail: "Domain Error Schemas do not support allOf unions".to_owned(),
        });
    }
    let variants = schema
        .get("oneOf")
        .and_then(Value::as_array)
        .filter(|variants| !variants.is_empty())
        .ok_or_else(|| CodegenError::UnsupportedSchema {
            path: source_path.to_path_buf(),
            detail: "Domain Error Schemas must be a non-empty oneOf union".to_owned(),
        })?;
    let mut codes = BTreeSet::new();
    let mut names = BTreeSet::from(["Unknown".to_owned()]);
    for variant in variants {
        if variant
            .as_object()
            .is_some_and(|object| object.contains_key("allOf"))
        {
            return Err(CodegenError::UnsupportedSchema {
                path: source_path.to_path_buf(),
                detail: "Domain Error variants do not support allOf unions".to_owned(),
            });
        }
        if let Some(code) = variant.get("const").and_then(Value::as_str) {
            let name = pascal_case(code);
            if !codes.insert(code.to_owned())
                || !names.insert(name.clone())
                || !is_generated_enum_variant(&name)
            {
                return Err(CodegenError::UnsupportedSchema {
                    path: source_path.to_path_buf(),
                    detail: format!("Domain Error code `{code}` is duplicated or name-colliding"),
                });
            }
            continue;
        }
        let object = variant
            .as_object()
            .ok_or_else(|| CodegenError::UnsupportedSchema {
                path: source_path.to_path_buf(),
                detail: "Domain Error variants must be string consts or objects".to_owned(),
            })?;
        let properties = object
            .get("properties")
            .and_then(Value::as_object)
            .ok_or_else(|| CodegenError::UnsupportedSchema {
                path: source_path.to_path_buf(),
                detail: "structured Domain Error variants need properties".to_owned(),
            })?;
        if object.get("additionalProperties") != Some(&Value::Bool(false))
            || !required_fields(variant).contains("code")
            || properties
                .keys()
                .any(|name| name != "code" && name != "payload")
        {
            return Err(CodegenError::UnsupportedSchema {
                path: source_path.to_path_buf(),
                detail:
                    "structured Domain Error objects must explicitly allow only code and payload"
                        .to_owned(),
            });
        }
        let code = object
            .get("properties")
            .and_then(Value::as_object)
            .and_then(|properties| properties.get("code"))
            .and_then(|code| code.get("const"))
            .and_then(Value::as_str)
            .ok_or_else(|| CodegenError::UnsupportedSchema {
                path: source_path.to_path_buf(),
                detail: "structured Domain Error variants need a const string code".to_owned(),
            })?;
        let name = pascal_case(code);
        if !codes.insert(code.to_owned())
            || !names.insert(name.clone())
            || !is_generated_enum_variant(&name)
        {
            return Err(CodegenError::UnsupportedSchema {
                path: source_path.to_path_buf(),
                detail: format!("Domain Error code `{code}` is duplicated or name-colliding"),
            });
        }
        if let Some(payload) = object
            .get("properties")
            .and_then(Value::as_object)
            .and_then(|properties| properties.get("payload"))
        {
            validate_value_generation_schema(payload, source_path)?;
        }
    }
    Ok(())
}

fn generation_input(path: &Path) -> Result<(GeneratedMetadata, ContractIr), CodegenError> {
    let descriptor = load_descriptor(path)?;
    let contract = contract_ir(&descriptor);
    let metadata = GeneratedMetadata {
        capability_id: descriptor.capability_id.clone(),
        descriptor_version: descriptor.version.clone(),
        descriptor_digest: descriptor.digest.clone(),
        portable: descriptor.portable,
        cross_lane_transfer: descriptor.cross_lane_transfer,
    };
    Ok((metadata, contract))
}

/// Generates one selected language projection from a Descriptor source.
pub fn generate_projection(
    path: &Path,
    language: ProjectionLanguage,
) -> Result<GeneratedProjection, CodegenError> {
    let (metadata, contract) = generation_input(path)?;
    let source = match language {
        ProjectionLanguage::Rust => generate_rust(&contract),
        ProjectionLanguage::TypeScript => generate_typescript(&contract),
        ProjectionLanguage::Wit => wit::generate_wit(&contract)?,
        ProjectionLanguage::RustRuntime => generate_rust_runtime(&contract)?,
        ProjectionLanguage::RustPlugin => generate_rust_plugin(&contract)?,
    };
    Ok(GeneratedProjection {
        metadata,
        language,
        source,
    })
}

/// Generates both language artifacts from one Descriptor source.
pub fn generate(path: &Path) -> Result<GeneratedArtifacts, CodegenError> {
    let (metadata, contract) = generation_input(path)?;
    Ok(GeneratedArtifacts {
        metadata,
        rust: generate_rust(&contract),
        typescript: generate_typescript(&contract),
    })
}

/// Writes generated artifacts to checked-in paths.
pub fn write_generated(
    descriptor_path: &Path,
    rust_path: &Path,
    typescript_path: &Path,
) -> Result<(), CodegenError> {
    let artifacts = generate(descriptor_path)?;
    write_artifact(rust_path, &artifacts.rust)?;
    write_artifact(typescript_path, &artifacts.typescript)?;
    Ok(())
}

/// Writes one selected language projection to a checked-in path.
pub fn write_projection(
    descriptor_path: &Path,
    language: ProjectionLanguage,
    output_path: &Path,
) -> Result<(), CodegenError> {
    let projection = generate_projection(descriptor_path, language)?;
    write_artifact(output_path, &projection.source)
}

/// Fails when either checked-in artifact is not exactly reproducible.
pub fn check_generated(
    descriptor_path: &Path,
    rust_path: &Path,
    typescript_path: &Path,
) -> Result<(), CodegenError> {
    let artifacts = generate(descriptor_path)?;
    check_artifact(rust_path, &artifacts.rust)?;
    check_artifact(typescript_path, &artifacts.typescript)?;
    Ok(())
}

